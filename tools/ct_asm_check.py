#!/usr/bin/env python3
"""Inspect generated assembly for conditional branches in constant-time gadgets.

This is supporting evidence, not a formal proof. It builds `sicas-core` for each
target at `-C opt-level=0`, extracts the assembly for `ct::eq_u32`,
`ct::select_u32`, and `ct::is_zero_u32`, and rejects conditional branches.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys

TARGETS = [
    "x86_64-unknown-linux-gnu",
    "aarch64-unknown-linux-gnu",
    "thumbv7em-none-eabihf",
    "riscv32imac-unknown-none-elf",
]

FUNCTIONS = ["eq_u32", "select_u32", "is_zero_u32"]

BRANCH_PATTERNS = {
    "x86_64-unknown-linux-gnu": re.compile(r"\b(j[a-z]+|loop[a-z]*)\b"),
    "aarch64-unknown-linux-gnu": re.compile(
        r"\b(b\.[a-z]+|cbz|cbnz|tbz|tbnz)\b"
    ),
    "thumbv7em-none-eabihf": re.compile(
        r"\b(b(?:eq|ne|cs|hs|cc|lo|mi|pl|vs|vc|hi|ls|ge|lt|gt|le)|cbz|cbnz|tbz|tbnz)\b"
    ),
    "riscv32imac-unknown-none-elf": re.compile(
        r"\b(?:c\.)?(?:beq|bne|blt|bge|bltu|bgeu|beqz|bnez|blez|bgez|bltz|bgtz|bgt|ble|bgtu|bleu)\b"
    ),
}


def build(target: str) -> pathlib.Path:
    subprocess.run(
        [
            "cargo",
            "rustc",
            "-p",
            "sicas-core",
            "--lib",
            "--target",
            target,
            "--",
            "--emit=asm",
            "-C",
            "opt-level=0",
        ],
        check=True,
        stdout=subprocess.DEVNULL,
    )
    deps = pathlib.Path("target") / target / "debug" / "deps"
    files = sorted(deps.glob("sicas_core-*.s"))
    if not files:
        raise SystemExit(f"no assembly file for {target} in {deps}")
    return files[-1]


def extract_function(assembly: str, function: str) -> str | None:
    lines = assembly.splitlines()
    start = None
    for index, line in enumerate(lines):
        if ".section" in line and "sicas_core2ct" in line and function in line:
            start = index
            break
    if start is None:
        return None

    end = start + 1
    while end < len(lines) and ".size" not in lines[end]:
        end += 1
    return "\n".join(lines[start : end + 1])


def find_branches(section: str, target: str) -> list[str]:
    pattern = BRANCH_PATTERNS[target]
    branches = []
    for match in pattern.finditer(section):
        instruction = match.group(0)
        if target == "x86_64-unknown-linux-gnu" and instruction == "jmp":
            continue
        branches.append(instruction)
    return sorted(set(branches))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=pathlib.Path)
    args = parser.parse_args()

    rows = []
    failures = 0
    for target in TARGETS:
        assembly_path = build(target)
        assembly = assembly_path.read_text(encoding="utf-8")
        for function in FUNCTIONS:
            section = extract_function(assembly, function)
            if section is None:
                rows.append((target, function, "MISSING", "FAIL"))
                failures += 1
                continue
            branches = find_branches(section, target)
            status = "pass" if not branches else "FAIL"
            if branches:
                failures += 1
            rendered = ", ".join(branches) if branches else "none"
            rows.append((target, function, rendered, status))

    lines = [
        "# Constant-Time Assembly Evidence",
        "",
        "Generated by `tools/ct_asm_check.py` at `-C opt-level=0`.",
        "",
        "| Target | Function | Conditional branches | Result |",
        "|---|---|---|---|",
    ]
    for target, function, branches, status in rows:
        lines.append(f"| {target} | `ct::{function}` | {branches} | {status} |")
    report = "\n".join(lines) + "\n"

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(report, encoding="utf-8")
    print(report)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
